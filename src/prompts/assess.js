// tokens  : 출력 상한. 분량 규정이 큰 문서일수록 넉넉히 잡아야 JSON 이 잘리지 않습니다.
// eta     : 예상 소요(초). 화면의 대기 안내에 씁니다.
//
// 이 문서는 8개 문단(영역 6 + 지원계획 + 부모면담)으로 80줄을 채웁니다.
// 문단을 배열이 아닌 "영역 6개 고정 + 별도 키 2개"로 받는 이유는 documents.js 의
// ASSESS_AREAS 참고 — 배열로 두면 모델이 영역을 빠뜨리거나 순서를 바꿉니다.

import { ASSESS_AREAS } from "../domain/documents.js";
import { CURRICULUM_GUIDE } from "../domain/curriculum.js";

/** 스키마의 areas 를 6영역 그대로 펼쳐 둡니다 — 모델이 빠뜨리지 못하게 */
