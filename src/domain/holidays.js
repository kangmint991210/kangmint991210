/** 공휴일 정보를 아는 해인가 (모르는 해는 아예 표시하지 않습니다 — 틀린 날짜보다 낫습니다) */
export const knowsHolidays = (year, table = BUILTIN_HOLIDAYS) => year in table;

/**
 * 받아 온 그 해의 공휴일을 얹은 "새" 표를 돌려줍니다.
 * 원래 표는 건드리지 않습니다 — 화면이 다시 그려질 때 값이 뒤섞이지 않도록.
 */
export function withYear(table, year, days) {
  if (!days || !Object.keys(days).length) return table;
  return { ...table, [year]: days };
}

/**
 * 그 날의 공휴일 이름. 공휴일이 아니거나 모르는 해면 null.
 * @param {string} key "YYYY-MM-DD"
 */
export function holidayOf(key, table = BUILTIN_HOLIDAYS) {
  if (!key) return null;
  const [year, ...rest] = key.split("-");
  return table[year]?.[rest.join("-")] || null;
}

/** 그 달의 공휴일들 — [{day, name}] (달력 아래 목록에 씁니다) */
export function holidaysInMonth({ year, month }, table = BUILTIN_HOLIDAYS) {
  const days = table[year];
  if (!days) return [];
  const mm = String(month).padStart(2, "0");
  return Object.entries(days)
    .filter(([md]) => md.startsWith(`${mm}-`))
    .map(([md, name]) => ({ day: Number(md.slice(3)), name }))
    .sort((a, b) => a.day - b.day);
}
