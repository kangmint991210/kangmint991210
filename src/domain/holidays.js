/** 공휴일 정보를 아는 해인가 (모르는 해는 표시하지 않습니다) */
export const knowsHolidays = (year) => year in BY_YEAR;

/**
 * 그 날의 공휴일 이름. 공휴일이 아니거나 모르는 해면 null.
 * @param {string} key "YYYY-MM-DD"
 */
export function holidayOf(key) {
  if (!key) return null;
  const [year, ...rest] = key.split("-");
  return BY_YEAR[year]?.[rest.join("-")] || null;
}

/** 그 달의 공휴일들 — [{day, name}] (달력 아래 목록에 씁니다) */
export function holidaysInMonth({ year, month }) {
  const table = BY_YEAR[year];
  if (!table) return [];
  const mm = String(month).padStart(2, "0");
  return Object.entries(table)
    .filter(([md]) => md.startsWith(`${mm}-`))
    .map(([md, name]) => ({ day: Number(md.slice(3)), name }))
    .sort((a, b) => a.day - b.day);
}
