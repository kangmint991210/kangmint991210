/** 프롬프트에 넣을 목록 문자열 — "영역 > 내용범주" 표기를 그대로 보여 줍니다. */
const toLines = (areas) =>
  Object.entries(areas)
    .map(([area, categories]) => `  · ${area} > ${categories.join(" / ")}`)
    .join("\n");

